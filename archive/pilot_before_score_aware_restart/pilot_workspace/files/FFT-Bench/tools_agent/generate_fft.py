#!/usr/bin/env python3
"""Generate self-contained synthesizable folded radix-2 FFT candidates."""
import argparse, math
from pathlib import Path
p=argparse.ArgumentParser()
p.add_argument('--width',type=int,default=22)
p.add_argument('--frac',type=int,default=15)
p.add_argument('--twfrac',type=int,default=14)
p.add_argument('--mul',type=int,choices=[3,4],default=4)
p.add_argument('--fused',action='store_true')
p.add_argument('--scale-from',type=int,default=6)
p.add_argument('--rne',action='store_true')
p.add_argument('--compact-coeff',action='store_true')
p.add_argument('--out',default='submission/rtl/fft64_top.sv')
a=p.parse_args();W=a.width; F=a.frac; TF=a.twfrac; C=TF+(1 if a.compact_coeff else 2)
assert 0<=15-F<=4 and W>=15 and 0<=a.scale_from<=6
rom='\n'.join(f"            5'd{k}: begin wr = {C}'sd{round(math.cos(2*math.pi*k/64)*(1<<TF))}; wi = {'-' if round(-math.sin(2*math.pi*k/64)*(1<<TF))<0 else ''}{C}'sd{abs(round(-math.sin(2*math.pi*k/64)*(1<<TF)))}; end".replace(f"= {C}'sd-",f"= -{C}'sd") for k in range(32))
if a.compact_coeff:
    rom=rom.replace(f"5'd0: begin wr = {C}'sd{1<<TF};",f"5'd0: begin wr = {C}'sd0;")
if a.mul==4:
    mult=f'''    wire signed [W+C-1:0] rr = br * wr;
    wire signed [W+C-1:0] ii = bi * wi;
    wire signed [W+C-1:0] ri = br * wi;
    wire signed [W+C-1:0] ir = bi * wr;
    wire signed [W+C:0] product_re = {{rr[W+C-1],rr}} - {{ii[W+C-1],ii}};
    wire signed [W+C:0] product_im = {{ri[W+C-1],ri}} + {{ir[W+C-1],ir}};'''
else:
    mult='''    wire signed [W:0] bs = {br[W-1],br} + {bi[W-1],bi};
    wire signed [C:0] cm = {wi[C-1],wi} - {wr[C-1],wr};
    wire signed [C:0] cp = {wr[C-1],wr} + {wi[C-1],wi};
    wire signed [W+C:0] m0 = bs * wr;
    wire signed [W+C:0] m1 = br * cm;
    wire signed [W+C:0] m2 = bi * cp;
    wire signed [W+C:0] product_re = m0 - m2;
    wire signed [W+C:0] product_im = m0 + m1;'''
shift=15-F
output_shift=shift+6-a.scale_from
inexpr=lambda s:f'$signed({s})' if not shift else f'(($signed({{{s}[15],{s}}}) + 17\'sd{1<<(shift-1)}) >>> {shift})'
# All data array writes pass through one write port per physical bank.
s=f'''// Generated by tools_agent/generate_fft.py. Exact logic except declared fixed-point rounding.
// Architecture: folded radix-2 DIT, parity-banked standard-cell storage.
module fft64_top (
    input wire clk, input wire rst, input wire in_valid, input wire frame_start,
    input wire signed [15:0] in_re, input wire signed [15:0] in_im,
    output reg out_valid, output reg out_start,
    output reg signed [23:0] out_re, output reg signed [23:0] out_im
);
    localparam W={W}, F={F}, C={C}, TF={TF}, SCALE_FROM={a.scale_from};
    localparam IDLE=2'd0, LOAD=2'd1, CALC=2'd2, EMIT=2'd3;
    reg [1:0] state;
    reg [5:0] sample;
    reg [4:0] butterfly;
    reg [2:0] stage;
    reg signed [W-1:0] bank0_re [0:31], bank0_im [0:31];
    reg signed [W-1:0] bank1_re [0:31], bank1_im [0:31];
    wire [5:0] input_number = (state == IDLE) ? 6'd0 : sample;
    wire [5:0] input_address = {{input_number[0],input_number[1],input_number[2],input_number[3],input_number[4],input_number[5]}};
    wire input_bank = ^input_address;
    wire signed [W-1:0] input_r = {inexpr('in_re')};
    wire signed [W-1:0] input_i = {inexpr('in_im')};
    reg [5:0] aa;
    reg [4:0] twiddle;
    always @* begin
        case (stage)
            3'd0: begin aa={{butterfly,1'b0}}; twiddle=0; end
            3'd1: begin aa={{butterfly[4:1],1'b0,butterfly[0]}}; twiddle={{butterfly[0],4'b0}}; end
            3'd2: begin aa={{butterfly[4:2],1'b0,butterfly[1:0]}}; twiddle={{butterfly[1:0],3'b0}}; end
            3'd3: begin aa={{butterfly[4:3],1'b0,butterfly[2:0]}}; twiddle={{butterfly[2:0],2'b0}}; end
            3'd4: begin aa={{butterfly[4],1'b0,butterfly[3:0]}}; twiddle={{butterfly[3:0],1'b0}}; end
            default: begin aa={{1'b0,butterfly}}; twiddle=butterfly; end
        endcase
    end
    wire [5:0] bb = aa | (6'd1 << stage);
    wire a_bank = ^aa;
    wire [4:0] raddr0 = (state == EMIT) ? sample[5:1] : (a_bank ? bb[5:1] : aa[5:1]);
    wire [4:0] raddr1 = (state == EMIT) ? sample[5:1] : (a_bank ? aa[5:1] : bb[5:1]);
    wire signed [W-1:0] r0=bank0_re[raddr0], i0=bank0_im[raddr0];
    wire signed [W-1:0] r1=bank1_re[raddr1], i1=bank1_im[raddr1];
    wire signed [W-1:0] ar=a_bank?r1:r0, ai=a_bank?i1:i0;
    wire signed [W-1:0] br=a_bank?r0:r1, bi=a_bank?i0:i1;
    reg signed [C-1:0] wr,wi;
    always @* begin
        case (twiddle)
{rom}
            default: begin wr=0; wi=0; end
        endcase
    end
{mult}
    wire signed [W+C:0] rounded_re = product_re + (1 << (TF-1));
    wire signed [W+C:0] rounded_im = product_im + (1 << (TF-1));
    wire signed [W-1:0] tr = (twiddle==0) ? br : ((twiddle==16) ? bi : (rounded_re >>> TF));
    wire signed [W-1:0] ti = (twiddle==0) ? bi : ((twiddle==16) ? -br : (rounded_im >>> TF));
    wire signed [W:0] full_sr={{ar[W-1],ar}}+{{tr[W-1],tr}};
    wire signed [W:0] full_si={{ai[W-1],ai}}+{{ti[W-1],ti}};
    wire signed [W:0] full_dr={{ar[W-1],ar}}-{{tr[W-1],tr}};
    wire signed [W:0] full_di={{ai[W-1],ai}}-{{ti[W-1],ti}};
    wire signed [W-1:0] sum_r = (stage>=SCALE_FROM) ? ((full_sr >>> 1) + (full_sr[0] & {"full_sr[1]" if a.rne else "1'b1"})) : full_sr;
    wire signed [W-1:0] sum_i = (stage>=SCALE_FROM) ? ((full_si >>> 1) + (full_si[0] & {"full_si[1]" if a.rne else "1'b1"})) : full_si;
    wire signed [W-1:0] dif_r = (stage>=SCALE_FROM) ? ((full_dr >>> 1) + (full_dr[0] & {"full_dr[1]" if a.rne else "1'b1"})) : full_dr;
    wire signed [W-1:0] dif_i = (stage>=SCALE_FROM) ? ((full_di >>> 1) + (full_di[0] & {"full_di[1]" if a.rne else "1'b1"})) : full_di;
    reg we0,we1;
    reg [4:0] wa0,wa1;
    reg signed [W-1:0] wd0r,wd0i,wd1r,wd1i;
    always @* begin
        we0=0; we1=0; wa0=0; wa1=0;
        wd0r=0; wd0i=0; wd1r=0; wd1i=0;
        if (((state==IDLE) && in_valid && frame_start) || ((state==LOAD) && in_valid)) begin
            we0=!input_bank; we1=input_bank;
            wa0=input_address[5:1]; wa1=input_address[5:1];
            wd0r=input_r; wd0i=input_i; wd1r=input_r; wd1i=input_i;
        end else if (state==CALC) begin
            we0=1; we1=1;
            wa0=a_bank?bb[5:1]:aa[5:1]; wa1=a_bank?aa[5:1]:bb[5:1];
            wd0r=a_bank?dif_r:sum_r; wd0i=a_bank?dif_i:sum_i;
            wd1r=a_bank?sum_r:dif_r; wd1i=a_bank?sum_i:dif_i;
        end
    end
    always @(posedge clk) begin
        if (!rst) begin
            if (we0) begin bank0_re[wa0]<=wd0r; bank0_im[wa0]<=wd0i; end
            if (we1) begin bank1_re[wa1]<=wd1r; bank1_im[wa1]<=wd1i; end
        end
        if (rst) begin
            state<=IDLE; sample<=0; butterfly<=0; stage<=0;
            out_valid<=0; out_start<=0; out_re<=0; out_im<=0;
        end else begin
            out_valid<=0; out_start<=0;
            case (state)
                IDLE: if (in_valid && frame_start) begin state<=LOAD; sample<=1; end
                LOAD: if (in_valid) begin
                    sample<=sample+1'b1;
                    if (sample==63) begin state<=CALC; stage<=0; butterfly<=0; end
                end
                CALC: begin
                    butterfly<=butterfly+1'b1;
                    if (butterfly==31) begin
                        stage<=stage+1'b1;
                        if (stage==5) begin state<=EMIT; sample<=0; end
                    end
                end
                EMIT: begin
                    out_valid<=1; out_start<=(sample==0);
                    out_re <= $signed((^sample)?r1:r0) * {1<<output_shift};
                    out_im <= $signed((^sample)?i1:i0) * {1<<output_shift};
                    sample<=sample+1'b1;
                    if (sample==63) state<=IDLE;
                end
            endcase
        end
    end
endmodule
'''
if a.fused:
    # Capture stage 0 during the last 32 input clocks, and emit the lower
    # half directly from stage 5. Only the upper half needs stored readout.
    s=s.replace("wire a_bank = ^aa;", "wire a_bank = (state==LOAD) ? !input_bank : (^aa);")
    s=s.replace("wire [4:0] raddr0 = (state == EMIT) ? sample[5:1] : (a_bank ? bb[5:1] : aa[5:1]);", "wire [4:0] raddr0 = (state==LOAD) ? input_address[5:1] : ((state == EMIT) ? sample[5:1] : (a_bank ? bb[5:1] : aa[5:1]));")
    s=s.replace("wire [4:0] raddr1 = (state == EMIT) ? sample[5:1] : (a_bank ? aa[5:1] : bb[5:1]);", "wire [4:0] raddr1 = (state==LOAD) ? input_address[5:1] : ((state == EMIT) ? sample[5:1] : (a_bank ? aa[5:1] : bb[5:1]));")
    s=s.replace("br=a_bank?r0:r1, bi=a_bank?i0:i1;", "br=(state==LOAD)?input_r:(a_bank?r0:r1), bi=(state==LOAD)?input_i:(a_bank?i0:i1);")
    s=s.replace("wa0=input_address[5:1]; wa1=input_address[5:1];\n            wd0r=input_r; wd0i=input_i; wd1r=input_r; wd1i=input_i;", "wa0=input_address[5:1]; wa1=input_address[5:1];\n            wd0r=input_r; wd0i=input_i; wd1r=input_r; wd1i=input_i;\n            if (state==LOAD && sample[5]) begin\n                we0=1; we1=1;\n                wd0r=a_bank?dif_r:sum_r; wd0i=a_bank?dif_i:sum_i;\n                wd1r=a_bank?sum_r:dif_r; wd1i=a_bank?sum_i:dif_i;\n            end")
    s=s.replace("state<=LOAD; sample<=1;", "state<=LOAD; sample<=1; stage<=0; butterfly<=0;")
    s=s.replace("state<=CALC; stage<=0; butterfly<=0;", "state<=CALC; stage<=1; butterfly<=0;")
    s=s.replace("CALC: begin\n                    butterfly<=", "CALC: begin\n                    if (stage==5) begin\n                        out_valid<=1; out_start<=(butterfly==0);\n                        out_re<=$signed(sum_r) * OUTPUT_FACTOR;\n                        out_im<=$signed(sum_i) * OUTPUT_FACTOR;\n                    end\n                    butterfly<=")
    s=s.replace("state<=EMIT; sample<=0;", "state<=EMIT; sample<=32;")
    s=s.replace("out_start<=(sample==0);", "out_start<=0;")
    s=s.replace("OUTPUT_FACTOR",str(1<<output_shift))
Path(a.out).parent.mkdir(parents=True,exist_ok=True);Path(a.out).write_text(s)
